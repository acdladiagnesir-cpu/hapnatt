for _cle, _valeur in INTERFACE.items():
    TEXTES.setdefault(_cle, _valeur)
MOTIFS = MOTIFS_INTERFACE + MOTIFS
MOTIFS = [(re.compile(m, re.S), t) for m, t in MOTIFS]
INVERSE = {v: k for k, v in TEXTES.items()}


def definir_langue(code):
    LANGUE["code"] = code


def T(texte):
    """Traduit un texte du français vers la langue active."""
    if LANGUE["code"] == "fr" or not isinstance(texte, str):
        return texte
    if texte in TEXTES:
        return TEXTES[texte]
    for motif, modele in MOTIFS:
        trouve = motif.fullmatch(texte)
        if trouve:
            return modele.format(*(T(g) for g in trouve.groups()))
    return texte


def origine(texte):
    """Retrouve la valeur française enregistrée dans les fichiers."""
    if LANGUE["code"] == "fr":
        return texte
    return INVERSE.get(texte, texte)
